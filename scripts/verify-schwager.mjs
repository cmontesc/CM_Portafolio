import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createServer } from 'vite';
import XLSX from 'xlsx';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
const server = await createServer({ configFile:false, server:{ middlewareMode:true,hmr:false,ws:false }, appType:'custom' });
try {
  const current=JSON.parse(fs.readFileSync('src/data/portfolioContent.json','utf8'));
  const project=current.projects.find(p=>p.id==='schwager-rediseño-web');
  const old=JSON.parse(fs.readFileSync('docs/backups/schwager-2026-09-11.json','utf8'));
  assert.equal(project.status,old.status); assert.equal(project.isPrincipal,old.isPrincipal);
  assert.equal(project.coverImage,old.coverImage); assert.deepEqual(project.caseStudy.interfaceImages,old.caseStudy.interfaceImages);
  assert.equal(new Set(current.projects.map(p=>p.id)).size,current.projects.length);
  const {validateEditorial,visibleResults,safeUrl}=await server.ssrLoadModule('/src/projectEditorial.ts');
  assert.equal(validateEditorial(project.caseStudy.editorial),undefined);
  assert.equal(safeUrl('javascript:alert(1)'),undefined);
  assert.equal(safeUrl('//evil.test',true),undefined);
  const e=project.caseStudy.editorial;
  assert.equal(visibleResults({...e,results:[{label:'X',description:'Y',type:'quantitative',visible:true,verified:false,value:'15%'}]}).length,0);
  assert.ok(validateEditorial({...e,decisionCases:[{finding:'X',decision:'Y',solution:'Z',image:'/uploads/a.png'}]}));
  const {EditorialCaseStudy}=await server.ssrLoadModule('/src/components/EditorialCaseStudy.tsx');
  const render=p=>renderToStaticMarkup(React.createElement(EditorialCaseStudy,{project:p}));
  const html=render(project);
  assert.equal((html.match(/Resultados y señales de impacto/g)||[]).length,1);
  assert.ok(!html.includes('+15%')); assert.ok(!html.includes('100%'));
  assert.ok(!html.includes('>Testimonio<')); assert.ok(!html.includes('>Antes y después<'));
  const empty={...project,caseStudy:{...project.caseStudy,editorial:{audiences:[{name:'',objective:'',need:''}],decisionCases:[{finding:'',decision:'',solution:''}],results:[],gallery:[]},designHighlights:['','Título | ']}};
  const emptyHtml=render(empty); assert.ok(!emptyHtml.includes('Audiencias del proyecto')); assert.ok(!emptyHtml.includes('Decisiones de interfaz')); assert.ok(!emptyHtml.includes('Resultados y señales'));
  const {projectToForm,buildProjectFromForm}=await server.ssrLoadModule('/src/admin/ProjectCmsPanel.tsx');
  const reopened=buildProjectFromForm(projectToForm(project));
  assert.deepEqual(JSON.parse(JSON.stringify(reopened)),project,'El formulario debe conservar todo el registro');
  const altered=projectToForm(project); altered.editorial=structuredClone(e); altered.editorial.audiences.reverse();
  altered.editorial.processSteps.push({title:'Prueba',description:'Temporal'}); altered.editorial.processSteps.pop();
  assert.deepEqual(buildProjectFromForm(altered).caseStudy.editorial.decisionCases,e.decisionCases);
  assert.deepEqual(buildProjectFromForm(altered).caseStudy.editorial.audiences,[...e.audiences].reverse());
  const {generateProjectsWorkbook,parseProjectsExcel}=await server.ssrLoadModule('/src/services/excelService.ts');
  const bytes=XLSX.write(generateProjectsWorkbook([project,current.projects[0]]),{type:'array',bookType:'xlsx'});
  const imported=await parseProjectsExcel(bytes);
  const restored=imported.allProjects.find(p=>p.id===project.id);
  assert.deepEqual(restored.caseStudy.editorial,e); assert.equal(restored.contentRevision,1);
  assert.deepEqual(restored.caseStudy.interfaceImages,project.caseStudy.interfaceImages); assert.deepEqual(restored.caseStudy.metrics,[]);
  assert.equal(imported.allProjects.find(p=>p.id===current.projects[0].id).caseStudy.editorial,undefined);
  assert.equal(fs.existsSync('dist/admin-local.html'),false);
  console.log('OK: formulario reversible, listas independientes, Excel ida/vuelta, secciones condicionales, resultados, enlaces y build sin admin.');
} finally { await server.close(); }
